import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
const [projectArg,privateArg]=process.argv.slice(2);
if(!projectArg||!privateArg)throw Error('Usage: npm run setup -- /absolute/new-project /absolute/new-private-dir');
if(!path.isAbsolute(projectArg)||!path.isAbsolute(privateArg))throw Error('Use absolute paths');
const project=path.resolve(projectArg),priv=path.resolve(privateArg);
if(priv===project||priv.startsWith(project+path.sep)||project.startsWith(priv+path.sep))throw Error('Project and private config must be separate');
const uid=process.getuid?.();const gid=process.getgid?.();if(!uid||gid===undefined)throw Error('Use a non-root Linux user');
const digest=JSON.parse(execFileSync('docker',['image','inspect','node:22-bookworm-slim','--format','{{json .RepoDigests}}'],{encoding:'utf8'})).find(x=>x.startsWith('node@sha256:'));
if(!digest)throw Error('Pull official node:22-bookworm-slim first');
await fs.mkdir(project,{mode:0o700});
await fs.mkdir(priv,{mode:0o700});
const token=crypto.randomBytes(32).toString('base64url');
await fs.writeFile(path.join(priv,'token'),token+'\n',{mode:0o600,flag:'wx'});
await fs.writeFile(path.join(priv,'tunnel-authorization'),'Bearer '+token+'\n',{mode:0o600,flag:'wx'});
await fs.writeFile(path.join(priv,'config.json'),JSON.stringify({project,user:`${uid}:${gid}`,image:'node:22-bookworm-slim@'+digest.split('@')[1],port:8791},null,2)+'\n',{mode:0o600,flag:'wx'});
console.log('Created an empty project and separate private config. Set CHAT_CODEX_CONFIG to '+path.join(priv,'config.json'));
